ALTER TABLE public.profiles
ADD COLUMN IF NOT EXISTS supabase_user_id UUID;

CREATE UNIQUE INDEX IF NOT EXISTS uq_profiles_supabase_user_id
ON public.profiles (supabase_user_id)
WHERE supabase_user_id IS NOT NULL;

ALTER TABLE public.profiles
ADD COLUMN IF NOT EXISTS role VARCHAR(20) NOT NULL DEFAULT 'student';

DO $$ BEGIN
    ALTER TABLE public.profiles
    ADD CONSTRAINT profiles_role_allowed
    CHECK (role IN ('student', 'faculty', 'admin'));
EXCEPTION WHEN duplicate_object THEN NULL;
END $$;

CREATE TABLE IF NOT EXISTS public.study_materials (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    title VARCHAR(200) NOT NULL,
    subject VARCHAR(100),
    original_filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(120) NOT NULL,
    content_sha256 VARCHAR(64) NOT NULL,
    published BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS study_materials_published_created_idx
ON public.study_materials (published, created_at DESC);

CREATE TABLE IF NOT EXISTS public.study_material_chunks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES public.study_materials(id) ON DELETE CASCADE,
    chunk_index INTEGER NOT NULL,
    content TEXT NOT NULL,
    keywords JSONB NOT NULL DEFAULT '[]'::jsonb,
    UNIQUE (material_id, chunk_index)
);

CREATE INDEX IF NOT EXISTS study_material_chunks_material_idx
ON public.study_material_chunks (material_id, chunk_index);

CREATE TABLE IF NOT EXISTS public.study_material_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES public.study_materials(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    notes JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.study_quiz_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES public.study_materials(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    questions JSONB NOT NULL,
    score INTEGER,
    submitted_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.study_quiz_responses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES public.study_quiz_sessions(id) ON DELETE CASCADE,
    material_id BIGINT NOT NULL REFERENCES public.study_materials(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    concept VARCHAR(120) NOT NULL,
    is_correct BOOLEAN NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS study_quiz_responses_student_concept_idx
ON public.study_quiz_responses (student_id, material_id, concept);

-- These tables are accessed through the authenticated backend, not directly
-- through Supabase's public REST API.
ALTER TABLE public.study_materials ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_material_chunks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_material_notes ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_quiz_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.study_quiz_responses ENABLE ROW LEVEL SECURITY;

