-- Apply after 003_ai_study_materials.sql in the Supabase SQL editor.
-- Persists RAG chat turns, retrieval configuration, citations, and explicit
-- learner source-support feedback for later inspection and comparison.
CREATE TABLE IF NOT EXISTS public.study_rag_interactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    material_id BIGINT NOT NULL REFERENCES public.study_materials(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.profiles(id) ON DELETE CASCADE,
    question TEXT NOT NULL,
    answer TEXT NOT NULL,
    rag_mode VARCHAR(20) NOT NULL CHECK (rag_mode IN ('standard', 'hybrid', 'adaptive')),
    retrieval_method VARCHAR(40) NOT NULL,
    citations JSONB NOT NULL DEFAULT '[]'::jsonb,
    diagnostics JSONB,
    supported_by_sources BOOLEAN,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS study_rag_interactions_student_material_mode_idx
ON public.study_rag_interactions (student_id, material_id, rag_mode, created_at DESC);

ALTER TABLE public.study_rag_interactions ENABLE ROW LEVEL SECURITY;

